"""Add the scoped organization's name to existing report covers.

Run in the report worker image with --apply after reviewing a dry run. The
original package PDF is saved alongside it before the public path is replaced.
"""
from __future__ import annotations

import argparse
from io import BytesIO
import hashlib
import itertools
import pathlib
import sys
import tempfile

from pypdf import PdfReader, PdfWriter
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen import canvas

import report_worker_cli as worker
import tenant_comparison as tenant


def cover_label_position(page) -> tuple[str, float]:
    found = []

    def visit(text, cm, tm, font, font_size):
        for label in ("Prepared by:", "Generated by:"):
            if label in text:
                found.append((label, float(tm[5])))

    page.extract_text(visitor_text=visit)
    current = [item for item in found if item[0] == "Generated by:"]
    if current:
        return current[-1]
    if len(found) != 1:
        raise ValueError(f"Expected one cover attribution label; found {len(found)}")
    return found[0]


def centered_line(c, label: str, value: str, y: float, width: float):
    font_size = min(11, 11 * 468 / max(width, 468))
    total = stringWidth(label, "Helvetica-Bold", font_size) + 4 + stringWidth(value, "Helvetica", font_size)
    x = (612 - total) / 2
    c.setFont("Helvetica-Bold", font_size)
    c.drawString(x, y, label)
    c.setFont("Helvetica", font_size)
    c.drawString(x + stringWidth(label, "Helvetica-Bold", font_size) + 4, y, value)


def update_pdf(source: bytes, org_name: str, on_demand_punchlist: bool = False) -> bytes | None:
    reader = PdfReader(BytesIO(source))
    if not reader.pages:
        raise ValueError("PDF has no pages")
    if (reader.metadata and reader.metadata.author == org_name and
            "Generated by:" in (reader.pages[0].extract_text() or "")):
        return None
    label, y = cover_label_position(reader.pages[0])

    overlay_bytes = BytesIO()
    c = canvas.Canvas(overlay_bytes, pagesize=(float(reader.pages[0].mediabox.width), float(reader.pages[0].mediabox.height)))
    c.setFillColorRGB(1, 1, 1)
    c.rect(72, y - 3, 468, 17, fill=1, stroke=0)
    if on_demand_punchlist:
        c.rect(72, y - 29, 468, 17, fill=1, stroke=0)
        c.setFillColorRGB(0, 0, 0)
        c.setFont("Helvetica-Bold", 11)
        c.drawCentredString(306, y, "Generated by:")
        size = min(11, 468 * 11 / max(stringWidth(org_name, "Helvetica", 11), 468))
        c.setFont("Helvetica", size)
        c.drawCentredString(306, y - 26, org_name)
    else:
        c.setFillColorRGB(0, 0, 0)
        width = stringWidth("Generated by:", "Helvetica-Bold", 11) + 4 + stringWidth(org_name, "Helvetica", 11)
        centered_line(c, "Generated by:", org_name, y, width)
    c.save()
    overlay_bytes.seek(0)

    writer = PdfWriter()
    writer.clone_document_from_reader(reader)
    writer.pages[0].merge_page(PdfReader(overlay_bytes).pages[0])
    metadata = {str(k): str(v) for k, v in (reader.metadata or {}).items() if v is not None}
    metadata["/Author"] = org_name
    writer.add_metadata(metadata)
    result = BytesIO()
    writer.write(result)
    updated = result.getvalue()
    checked = PdfReader(BytesIO(updated))
    if len(checked.pages) != len(reader.pages) or "Generated by:" not in (checked.pages[0].extract_text() or "") or checked.metadata.author != org_name:
        raise ValueError("Updated PDF failed verification")
    return updated


def report_rows(client, table: str, columns: str, filters: dict[str, str]):
    cursor = ""
    while True:
        query = {"select": columns, **filters, "order": "id.asc", "limit": "50"}
        if cursor:
            query["id"] = f"gt.{cursor}"
        rows = client.select(table, query)
        if not rows:
            break
        yield from rows
        cursor = rows[-1]["id"]


def package_reports(client):
    columns = "id,package_id,org_id,property_id,session_id,report_type,storage_bucket,storage_path,mime_type,sha256,byte_size"
    for row in report_rows(client, "report_package_files", columns, {"deleted_at": "is.null", "storage_deleted_at": "is.null"}):
        if row["storage_bucket"] != worker.DELIVERABLES_BUCKET or row["mime_type"] != "application/pdf":
            continue
        expected = worker.path_for_pdf(row["org_id"], row["property_id"], row["session_id"], row["package_id"], row["report_type"])
        if row["storage_path"] != expected:
            raise ValueError(f"Unexpected package PDF path for {row['id']}")
        packages = client.select("report_packages", {"select": "id", "id": f"eq.{row['package_id']}", "status": "eq.ready", "deleted_at": "is.null", "limit": "1"})
        if packages:
            yield row, worker.DELIVERABLES_BUCKET, expected, False


def on_demand_reports(client):
    columns = "id,org_id,property_id,kind,status,storage_path,expires_at"
    for row in report_rows(client, "on_demand_report_requests", columns, {"status": "eq.ready", "expires_at": f"gt.{worker.safe_iso_now()}"}):
        if row["kind"] not in ("punchlist_all", "tenant_comparison") or not row.get("storage_path"):
            continue
        expected = tenant.expected_path(row)
        if row["storage_path"] != expected:
            raise ValueError(f"Unexpected on-demand PDF path for {row['id']}")
        yield row, tenant.BUCKET, expected, row["kind"] == "punchlist_all"


def migrate(client, apply: bool, limit: int = 0):
    counts = {"checked": 0, "updated": 0, "already_current": 0, "failed": 0}
    org_names = {}
    for row, bucket, path, punchlist in itertools.chain(package_reports(client), on_demand_reports(client)):
        if limit and counts["checked"] >= limit:
            break
        counts["checked"] += 1
        updated = None
        try:
            if row["org_id"] not in org_names:
                org_names[row["org_id"]] = worker.generating_organization_name(client, row["org_id"])
            original = client.download_object(bucket, path)
            updated = update_pdf(original, org_names[row["org_id"]], punchlist)
            if updated is None:
                counts["already_current"] += 1
                continue
            if apply:
                backup = f"report-attribution-backups/{row['id']}.pdf"
                if not client.object_exists(bucket, backup):
                    original_path = pathlib.Path(tempfile.gettempdir()) / f"{row['id']}-original.pdf"
                    original_path.write_bytes(original)
                    try:
                        client.upload_object(bucket, backup, original_path, "application/pdf", upsert=False)
                    finally:
                        original_path.unlink(missing_ok=True)
                updated_path = pathlib.Path(tempfile.gettempdir()) / f"{row['id']}-attributed.pdf"
                updated_path.write_bytes(updated)
                try:
                    client.upload_object(bucket, path, updated_path, "application/pdf", upsert=True)
                finally:
                    updated_path.unlink(missing_ok=True)
                if hashlib.sha256(client.download_object(bucket, path)).digest() != hashlib.sha256(updated).digest():
                    raise ValueError("Uploaded PDF checksum did not match")
                if bucket == worker.DELIVERABLES_BUCKET:
                    client.patch("report_package_files", {"id": f"eq.{row['id']}"},
                                 {"byte_size": len(updated), "sha256": hashlib.sha256(updated).hexdigest()})
            counts["updated"] += 1
        except Exception as exc:
            counts["failed"] += 1
            print(f"{row['id']}: {type(exc).__name__}: {exc}", file=sys.stderr)
            continue
        print(f"{row['id']}: {'applied' if apply else 'would update'}" if updated is not None else f"{row['id']}: current")
    print(worker.stable_json({"mode": "apply" if apply else "dry_run", **counts}))
    return counts["failed"] == 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--limit", type=int, default=0)
    args = parser.parse_args()
    if args.limit < 0:
        parser.error("--limit must be nonnegative")
    url = worker.os.environ.get("SUPABASE_URL", "").strip()
    key = worker.os.environ.get("SUPABASE_SERVICE_ROLE_KEY", "").strip()
    if not url or not key:
        parser.error("SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required")
    client = worker.SupabaseServiceClient(url, key, "production")
    return 0 if migrate(client, args.apply, args.limit) else 1


if __name__ == "__main__":
    sys.exit(main())
