from io import BytesIO
import importlib.util
from pathlib import Path
import sys
import unittest

from pypdf import PdfReader
from reportlab.pdfgen import canvas

ROOT = Path(__file__).resolve().parents[1] / 'report-production'
sys.path.insert(0, str(ROOT))
spec = importlib.util.spec_from_file_location('backfill_report_organization', ROOT / 'backfill_report_organization.py')
backfill = importlib.util.module_from_spec(spec)
spec.loader.exec_module(backfill)


def old_pdf(punchlist=False):
    data = BytesIO()
    c = canvas.Canvas(data, pagesize=(612, 792))
    c.setFont('Helvetica-Bold', 11)
    c.drawString(210, 180, 'Prepared by:')
    c.setFont('Helvetica', 11)
    c.drawString(281, 180 if not punchlist else 154, 'Old Capture Group')
    c.showPage()
    c.drawString(72, 720, 'Issue details are preserved')
    c.save()
    return data.getvalue()


class BackfillReportOrganizationTests(unittest.TestCase):
    def test_package_report_updates_cover_and_metadata_without_losing_pages(self):
        result = backfill.update_pdf(old_pdf(), 'Current Example Group')
        pdf = PdfReader(BytesIO(result))
        self.assertEqual(len(pdf.pages), 2)
        self.assertIn('Generated by:', pdf.pages[0].extract_text())
        self.assertIn('Current Example Group', pdf.pages[0].extract_text())
        self.assertIn('Issue details are preserved', pdf.pages[1].extract_text())
        self.assertEqual(pdf.metadata.author, 'Current Example Group')
        self.assertIsNone(backfill.update_pdf(result, 'Current Example Group'))

    def test_on_demand_punchlist_updates_two_line_cover(self):
        result = backfill.update_pdf(old_pdf(punchlist=True), 'Current Example Group', True)
        pdf = PdfReader(BytesIO(result))
        self.assertEqual(pdf.metadata.author, 'Current Example Group')
        self.assertIn('Current Example Group', pdf.pages[0].extract_text())


if __name__ == '__main__':
    unittest.main()
